"""Managed, alarm-free single-camera observation using the candidate image."""
import argparse,csv,json,logging,queue,signal,threading,time
from datetime import datetime,timedelta,timezone
from pathlib import Path
import cv2,cupy,yaml
from pyservicemaker import Pipeline,BufferRetriever,Receiver
from server.pipeline.builder import PipelineBuilder
from server.pipeline.probe import SafetyProbe
from loguru import logger

ap=argparse.ArgumentParser();ap.add_argument("--camera",default="2676")
ap.add_argument("--out",default="/app/output");ap.add_argument("--interval",type=float,default=10)
a=ap.parse_args();out=Path(a.out).resolve();out.mkdir(parents=True,exist_ok=True)
logging.basicConfig(level=logging.INFO,format="%(asctime)s %(levelname)s %(message)s",
                    handlers=[logging.FileHandler(out/"observer.log"),logging.StreamHandler()])
stop=threading.Event();work=queue.Queue(maxsize=2);tz=timezone(timedelta(hours=8))
for sig in (signal.SIGINT,signal.SIGTERM):signal.signal(sig,lambda *_:stop.set())
cfg=yaml.safe_load(Path("/app/deploy/config.yaml").read_text())
cfg["cameras"]=[c for c in cfg["cameras"] if str(c["id"])==a.camera]
if len(cfg["cameras"])!=1:raise RuntimeError("Expected exactly one camera")
cfg["cameras"][0]["enabled"]=True;cfg.setdefault("source",{})["preserve_bitstream"]=True
# This script never builds alert managers, attaches alarm probes or calls VLM/webhooks.
class Capture(BufferRetriever):
 def __init__(self):super().__init__();self.next_at=0;self.count=0;self.last_frame=0
 def consume(self,buffer):
  self.count+=1;self.last_frame=time.monotonic()
  now=time.monotonic()
  if now<self.next_at:return 1
  self.next_at=now+a.interval
  try:
   meta=next(iter(buffer.batch_meta.frame_items),None);objects=[]
   if meta is not None:
    for obj in meta.object_items:
     uid=int(obj.unique_component_id)
     if uid not in (1,3):continue
     label=str(getattr(obj,"label","") or ("person" if uid==1 else "unknown"))
     box=[float(obj.rect_params.left),float(obj.rect_params.top),
          float(obj.rect_params.left+obj.rect_params.width),float(obj.rect_params.top+obj.rect_params.height)]
     vest=SafetyProbe._classifier_label(obj.classifier_items,6) if uid==1 else None
     objects.append({"uid":uid,"label":label,"confidence":float(obj.confidence),"bbox":box,"vest":vest})
   item=(buffer.extract(0).clone(),objects,int(getattr(meta,"frame_number",-1)),
         int(getattr(meta,"buffer_pts",0)),datetime.now(tz).isoformat())
   try:work.put_nowait(item)
   except queue.Full:logging.warning("snapshot writer busy; skipped sample")
  except Exception:logging.exception("capture failed")
  return 1

capture=Capture();saved=0

def writer():
 global saved
 csvpath=out/"samples.csv"
 with csvpath.open("a",encoding="utf-8-sig",newline="") as f:
  w=csv.writer(f)
  if csvpath.stat().st_size==0:w.writerow(["time_bjt","frame","pts","raw_file","annotated_file","person","head","helmet","green_fraction"])
  while not stop.is_set() or not work.empty():
   try:t,objects,fn,pts,stamp=work.get(timeout=.5)
   except queue.Empty:continue
   try:
    raw=cv2.cvtColor(cupy.from_dlpack(t).get(),cv2.COLOR_RGB2BGR);vis=raw.copy()
    tag=datetime.fromisoformat(stamp).strftime("%Y%m%d_%H%M%S_%f")+f"_f{fn}"
    counts={label:sum(o["label"]==label for o in objects) for label in ("person","head","helmet")}
    for o in objects:
     box=list(map(int,o["bbox"]));color=(0,0,255) if o["label"]=="head" else (0,220,220) if o["label"]=="helmet" else (0,220,0)
     cv2.rectangle(vis,(box[0],box[1]),(box[2],box[3]),color,2)
     label=f"{o['label']} {o['confidence']:.2f}"+(f" {o['vest']}" if o["vest"] else "")
     cv2.putText(vis,label,(max(0,box[0]),max(15,box[1]-5)),cv2.FONT_HERSHEY_SIMPLEX,.55,color,2)
    names=[f"raw_{tag}.jpg",f"annotated_{tag}.jpg"]
    for name,image in zip(names,[raw,vis]):
     if not cv2.imwrite(str(out/name),image,[cv2.IMWRITE_JPEG_QUALITY,90]):raise RuntimeError("Image write failed")
    b,g,r=cv2.split(raw);green=float(((g.astype('int16')>r.astype('int16')+40)&(g.astype('int16')>b.astype('int16')+40)&(g>150)).mean())
    meta={"camera":a.camera,"time_bjt":stamp,"frame":fn,"pts":pts,"objects":objects,"green_fraction":green,"model":cfg["model"]["gies"]["helmet"]["source"]}
    (out/f"meta_{tag}.json").write_text(json.dumps(meta,ensure_ascii=False,indent=2))
    w.writerow([stamp,fn,pts,*names,counts["person"],counts["head"],counts["helmet"],round(green,6)]);f.flush()
    saved+=1
    (out/"status.json").write_text(json.dumps({"camera":a.camera,"last_sample":stamp,"frame":fn,"samples_this_run":saved,"frames_this_run":capture.count,"interval_seconds":a.interval,"no_webhooks":True,"no_vlm":True}))
    logging.info("saved camera=%s frame=%s person=%s head=%s helmet=%s green=%.6f",a.camera,fn,counts["person"],counts["head"],counts["helmet"],green)
    # Retire only files generated by this observer, inside its dedicated output directory.
    cutoff=time.time()-86400
    for old in out.glob("raw_*.jpg"):
     if old.stat().st_mtime>=cutoff:continue
     stem=old.name[4:-4]
     for name in (f"raw_{stem}.jpg",f"annotated_{stem}.jpg",f"meta_{stem}.json"):
      target=(out/name).resolve()
      if target.parent==out and target.is_file():target.unlink()
   except Exception:logging.exception("snapshot write failed")
   finally:work.task_done()

p=Pipeline("observe-"+a.camera);builder=PipelineBuilder(cfg,Path("/app/deploy"))
builder._add_sources(p,logger);builder._add_inference_chain(p)
p.add("nvvideoconvert","capture-conv",{"gpu-id":0,"compute-hw":1})
p.add("capsfilter","capture-caps",{"caps":"video/x-raw(memory:NVMM), format=RGB"})
p.add("appsink","capture-sink",{"emit-signals":True,"sync":False,"async":0})
p.link(("demux","capture-conv"),("src_%u",""));p.link("capture-conv","capture-caps","capture-sink")
p.attach("capture-sink",Receiver("capture",capture),tips="new-sample")
thread=threading.Thread(target=writer,daemon=True);thread.start()
logging.info("starting camera=%s interval=%ss no_webhooks=true no_vlm=true",a.camera,a.interval)
p.start();started=time.monotonic()
while not stop.wait(5):
 if time.monotonic()-max(capture.last_frame,started)>180:
  logging.error("no decoded frames for 180 seconds; exit for container restart")
  raise SystemExit(1)
logging.info("stopping observer");p.stop();thread.join(timeout=5)
